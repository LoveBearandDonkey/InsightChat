/* Build-time dependency only. Runtime uses a checked-in, same-origin snapshot. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {createHash} = require('node:crypto');
const {execFileSync} = require('node:child_process');
const root = path.resolve(__dirname, '..');
const upstream = path.resolve(process.env.MINDSPEED_CONFIG_MCP_ROOT || path.join(root, '../mindspeed-config-mcp'));
const sourcePath = 'apps/web/prototypes/constraint-lens.html';
const html = fs.readFileSync(path.join(upstream, sourcePath), 'utf8');
assert.ok(html.includes('mindspeed-constraint-lens/v1'), 'Upstream must support the inline v1 contract');
const tabs = [...html.matchAll(/<button role="tab"[^>]*data-case="([^"]+)"[^>]*>([^<]+)<\/button>/g)];
assert.equal(tabs.length, 5, 'Expected exactly five source tabs');
const rounds = tabs.map(([,id,label]) => {
  const escaped = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const question = html.match(new RegExp(`(?:'${escaped}'|${escaped}):\\{[^\\n]*?question:'([^']+)'`))?.[1];
  assert.ok(question, `Missing original question for ${id}`);
  return {id, label, question};
});
let revision = null;
try { revision = execFileSync('git', ['-C', upstream, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim(); } catch {}
const sha256 = createHash('sha256').update(html).digest('hex');
const source_content_sha256 = createHash('sha256').update(html.replace(/\r\n/g,'\n')).digest('hex');
const manifest = {schema_version:1, channel:'mindspeed-constraint-lens/v1', source_repository:'mindspeed-config-mcp', source_path:sourcePath, source_revision:revision, sha256, source_content_sha256, execution_mode:'constructed-history-local-prototype', mcp_protocol_invoked:false, rounds};
const history = {id:'constraint-lens-five-rounds', title:'MindSpeed 配置约束 · 五轮对话', url:'vendor/constraint-lens/index.html', rounds};
const target = path.join(root, 'demo/vendor/constraint-lens');
const files = new Map([
  ['index.html', html],
  ['manifest.json', JSON.stringify(manifest,null,2)+'\n'],
  ['history.js', '/* Generated by npm run sync:constraint-lens. */\nwindow.MS_CONSTRAINT_HISTORY = '+JSON.stringify(history,null,2)+';\n'],
]);
if(process.argv.includes('--check')) {
  for(const [name,content] of files) {
    let actual=fs.readFileSync(path.join(target,name),'utf8');
    if(name==='manifest.json') {
      // A new HEAD alone does not change the page. Freshness is defined by content.
      const recorded=JSON.parse(actual);recorded.source_revision=revision;
      const targetHtml=fs.readFileSync(path.join(target,'index.html'));
      assert.equal(recorded.sha256,createHash('sha256').update(targetHtml).digest('hex'),'Constraint lens checksum mismatch');
      // Preserve the byte checksum but compare source content across Git EOL modes.
      recorded.sha256=sha256;
      actual=JSON.stringify(recorded,null,2)+'\n';
    }
    assert.equal(actual.replace(/\r\n/g,'\n'),content.replace(/\r\n/g,'\n'), `Stale snapshot: ${name}; run npm run sync:demo-assets`);
  }
  console.log('Five rounds and source snapshot verified; SHA256 '+sha256);
} else {
  fs.mkdirSync(target,{recursive:true});
  for(const [name,content] of files) fs.writeFileSync(path.join(target,name),content);
  console.log('Synced five original tabs; SHA256 '+sha256);
}
