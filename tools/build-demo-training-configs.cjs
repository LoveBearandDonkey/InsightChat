/* Bundle local training samples for the demo, including file:// previews. */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '../demo/training-configs');
const files = {};
function collect(directory, prefix) {
  for (const entry of fs.readdirSync(directory, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name))) {
    const relative = `${prefix}/${entry.name}`;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) collect(absolute, relative);
    else if (entry.isFile()) files[relative] = fs.readFileSync(absolute, 'utf8');
  }
}
for (const entry of fs.readdirSync(root, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name))) {
  if (entry.isDirectory()) collect(path.join(root, entry.name), `ConfigTest/${entry.name}`);
}
fs.writeFileSync(path.join(root, 'workspace.js'),
  '/* Generated by tools/build-demo-training-configs.cjs from local samples. */\n' +
  `window.DEMO.trainingFiles = ${JSON.stringify(files, null, 2)};\n` +
  'Object.assign(window.DEMO.files, window.DEMO.trainingFiles);\n');
console.log(`Bundled ${Object.keys(files).length} local training configuration files.`);
